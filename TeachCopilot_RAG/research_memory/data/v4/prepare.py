def write_rows(path, rows):
    path.write_text("".join(json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n"
                            for row in rows), encoding="utf-8")


def background(seed, index):
    """Meaningful calculation and checking episodes, not repeated text padding."""
    quotients = [124, 136, 147, 158, 162, 174, 186, 192, 213, 216, 234, 246,
                 312, 324, 342, 364, 412, 426, 432, 438, 462, 468, 472, 486]
    divisors = [3, 4, 6, 7, 8, 9, 12, 14, 16, 18, 21, 24]
    q = quotients[(seed * 5 + index * 3) % len(quotients)]
    d = divisors[(seed + index * 2) % len(divisors)]
    n = q * d
    h, t, u = q // 100 * 100, q // 10 % 10 * 10, q % 10
    return [
        ("teacher", f"Отдельная карточка {n} : {d}. Выполни деление, затем выбери свой способ проверки. Сейчас я наблюдаю работу, не даю готовой записи и не задаю наводящих вопросов. Можно объяснять разложение чисел своими словами."),
        ("student", f"В частном получилось {q}. Для проверки разложил ответ: {h} + {t} + {u}. Произведения частей на {d}: {h*d}, {t*d} и {u*d}; их сумма {n}. Это совпало с делимым. Каждую цифру частного сверил со своим разрядом."),
        ("teacher", f"Вычисление {n} : {d} = {q} и обратная проверка верны. Ученик выполнял эту карточку самостоятельно, я проверил после завершения. Обсуждаем именно эту запись с частным {q}, а не условия каких-либо прежних карточек."),
        ("student", f"В произведении {q} × {d} удобнее сначала умножить сотни, затем десятки и единицы; {h*d} + {t*d} + {u*d} = {n}. Обратная проверка показывает совпадение для моей сегодняшней карточки. Здесь в частном записаны три ненулевые цифры."),
    ]


def build():
    histories, requests, gold, design = [], [], [], []
    for number, (situation, length, key_lessons, facts, actions, prohibited, concrete) in enumerate(SCENARIOS, 1):
        hid = f"t{number:02d}"
        lessons = list(key_lessons)
        if length == "long":
            # Corrected sources, a fresh independent attempt, progress and an
            # unfinished task are recent; early assistance/unknowns/ownership
            # compete with six later, relevant arithmetic episodes.
            filler = [background(number, index) for index in range(6)]
            if situation in {"source_correction", "independent_attempt", "real_progress", "unfinished"}:
                lessons = key_lessons[:1] + filler + key_lessons[1:]
            else:
                lessons += filler
        source_lessons = []
        key_ids = []
        for index, turns in enumerate(lessons, 1):
            lid = f"{hid}-l{index:02d}"
            source_turns = [{"turn_id": f"{lid}-t{k:02d}", "role": role, "text": text}
                            for k, (role, text) in enumerate(turns, 1)]
            source_lessons.append({"lesson_id": lid,
                                   "observed_on": (date(2026, 6, 1) + timedelta(days=7*(index-1))).isoformat(),
                                   "turns": source_turns})
            if turns in key_lessons:
                key_ids.extend(turn["turn_id"] for turn in source_turns)
        history = {"history_id": hid, "learner_id": f"synthetic-heldout-{number:02d}",
                   "split": "test", "data_origin": "synthetic_unreviewed",
                   "profile_as_of_cutoff": dict(PROFILE), "lessons": source_lessons}
        histories.append(history)
        for index, question in enumerate(REQUESTS, 1):
            rid = f"{hid}-q{index:02d}"
            requests.append({"request_id": rid, "history_id": hid, "topic_id": TOPIC, "text": question})
            gold.append({"request_id": rid, "required_facts": facts, "allowed_actions": actions,
                         "forbidden_claims": prohibited, "evidence_turn_ids": key_ids,
                         "acceptable_action_examples": concrete,
                         "notes": "Предварительная рубрика агента, содержательно не проверена человеком. Пересказ всех фактов не обязателен. Допустимы иные соразмерные действия с верным основанием; enum не задаёт единственный правильный ответ. Пустой unknowns и review_required=true сами по себе не являются искажением."})
        full, limited = Memory("tail", None, 100000, TOPIC), Memory("tail", None, 4000, TOPIC)
        for lesson in source_lessons:
            full.update(lesson)
            limited.update(lesson)
        full_context, limited_context = full.context(TOPIC), limited.context(TOPIC)
        text_length = sum(len(turn["text"]) for lesson in source_lessons for turn in lesson["turns"])
        assert (text_length > 4000) == (length == "long"), (hid, text_length)
        design.append({"history_id": hid, "situation": situation, "length": length,
                       "source_text_chars": text_length, "full_tail_chars": len(full_context.text),
                       "selected_tail_chars": len(limited_context.text), "key_turn_ids": key_ids,
                       "key_turn_ids_visible_in_tail": sorted(set(key_ids) & limited_context.evidence_ids),
                       "lesson_count": len(source_lessons)})
    write_rows(HERE / "histories.test.jsonl", histories)
    write_rows(HERE / "requests.test.jsonl", requests)
    write_rows(HERE / "gold.test.jsonl", gold)
    (HERE / "design.private.json").write_text(json.dumps({
        "data_origin": "synthetic_unreviewed", "human_semantic_review": False,
        "scenario_count": 16, "requests_per_history": 2, "expected_answer_count": 128,
        "independent_observation_unit": "history; compare methods within history; do not count answers as independent learners",
        "design": design}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    selection = {"selection_origin": "preselected before generation", "human_semantic_review": False,
                 "seed": 20261017, "expected_answers": 20, "methods": list(METHODS),
                 "requests": ["t02-q01", "t04-q01", "t07-q01", "t10-q01", "t12-q01"],
                 "disputes": "all generation failures, judge errors, uncertain verdicts and factual critical_error findings"}
    (HERE / "review.selection.json").write_text(json.dumps(selection, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    calibration()
    files = ("histories.test.jsonl", "requests.test.jsonl", "gold.test.jsonl", "design.private.json",
             "calibration.cases.jsonl", "calibration.expected.jsonl", "review.selection.json")
    manifest = {"protocol": "heldout-v4", "judge_protocol": "context-v3",
                "status": "prepared_before_generation", "human_semantic_review": False,
                "generator_inputs": ["histories.test.jsonl", "requests.test.jsonl"],
                "excluded_from_generator": [name for name in files if name not in {"histories.test.jsonl", "requests.test.jsonl"}],
                "sha256": {name: hashlib.sha256((HERE / name).read_bytes()).hexdigest() for name in files}}
    (HERE / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


