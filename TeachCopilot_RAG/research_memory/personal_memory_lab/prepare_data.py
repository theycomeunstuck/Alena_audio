def build():
    histories, requests, gold = [], [], []
    for number, story in enumerate(STORIES, 1):
        history_id = f"pm-h{number:02d}"
        split = "dev" if number <= 3 else "heldout"
        events = [("error", story["error"]), ("early", story["early"]),
                  ("fact", story["fact"]), ("other0", story["other"][0]),
                  ("other1", story["other"][1]), ("late", story["late"]),
                  ("ambiguous", story["ambiguous"]), ("other2", story["other"][2]),
                  ("unfinished", story["unfinished"]), ("other3", story["other"][3])]
        if number % 2 == 0:
            events[2], events[3] = events[3], events[2]
            events[6], events[7] = events[7], events[6]
        lessons, by_kind = [], {}
        for index, (kind, texts) in enumerate(events, 1):
            lesson_id = f"{history_id}-l{index:02d}"
            turns = [{"turn_id": f"{lesson_id}-t{j:04d}",
                      "role": "teacher" if j % 2 else "student", "text": text}
                     for j, text in enumerate(texts, 1)]
            by_kind[kind] = [item["turn_id"] for item in turns]
            # Two deliberately long stress histories. These extra exercises are
            # mechanical distractors, so their length is not a naturalism claim.
            if number in (2, 5):
                for extra in range(130):
                    left = 11 + (index * 137 + extra * 7) % 75
                    right = 3 + (index * 31 + extra * 3) % 16
                    texts_extra = [f"Устная разминка {index}-{extra + 1}: сколько будет {left} плюс {right}? Покажи проверку обратным действием.",
                                   f"Получится {left + right}. Проверяю: {left + right} минус {right} равно {left}."]
                    for text in texts_extra:
                        j = len(turns) + 1
                        turns.append({"turn_id": f"{lesson_id}-t{j:04d}",
                                      "role": "teacher" if j % 2 else "student", "text": text})
            lessons.append({"lesson_id": lesson_id, "observed_on": (date(2026, 1, 5) + timedelta(days=index*3)).isoformat(),
                            "topic_ids": [story["topic"]], "turns": turns})
        profile = {"grade": story["grade"], "status": "learning", "topic_id": story["topic"],
                   "allowed_topic_ids": [story["topic"]], "topic_edges": []}
