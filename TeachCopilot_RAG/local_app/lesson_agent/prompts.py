def summary_messages(profile: dict, lesson: str, transcript: dict) -> list[dict[str, str]]:
    """Build the summary messages; transcript keeps omitted-turn honesty."""
    return [
        {"role": "system", "content": SUMMARY_SYSTEM_PROMPT},
        {"role": "user", "content": (
            "Профиль (JSON): " + json.dumps(profile, ensure_ascii=False)
            + "\n\nУрок:\n" + (lesson[:12000] or "Готовый урок не создавался.")
            + "\n\nПереписка (JSON): " + json.dumps(transcript, ensure_ascii=False)
        )},
    ]
