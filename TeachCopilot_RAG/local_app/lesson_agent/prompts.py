LESSON_START_REQUEST = (
    "Начни подготовленный урок сейчас. Коротко назови тему, проведи только "
    "первый шаг разминки и задай один конкретный вопрос ребёнку. Дождись его "
    "ответа, прежде чем переходить к объяснению и следующим заданиям. "
    "Не раскрывай раздел с ответами."
)


def guided_messages(profile: dict, lesson_context: str, guided_mode: bool,
                    history: list[dict[str, str]], question: str) -> list[dict[str, str]]:
    """Build the guided chat messages with the server-owned lesson context."""
    lesson_mode = ("Активен: проводи подготовленный урок по шагам."
                   if guided_mode else "Свободный учебный диалог.")
    system = GUIDED_CHAT_SYSTEM_PROMPT.replace("{lesson_mode}", lesson_mode)
    system += "\n\nПрофиль ребёнка (JSON): " + json.dumps(profile, ensure_ascii=False)
    system += "\n\nТекущий урок (если уже создан):\n" + (lesson_context[:12000] or "Урок ещё не создан.")
    messages = [{"role": "system", "content": system}]
    for turn in history:
        messages.append({"role": turn["role"], "content": turn["content"]})
    messages.append({"role": "user", "content": question})
    return messages


